# --- backgrounds ----------------------------------------------------------------------------------

def _lowfreq(shape: tuple[int, int], rng: np.random.Generator, cells: int = 10) -> np.ndarray:
    h, w = shape
    small = rng.standard_normal((cells, max(2, round(cells * w / h)))).astype(np.float32)
    img = Image.fromarray(small).resize((w, h), Image.BICUBIC)
    arr = np.asarray(img, dtype=np.float32)
    return (arr - arr.mean()) / (arr.std() + 1e-6)


def plain_wall(key: str, size: tuple[int, int] = CANVAS, seed: int = 7) -> np.ndarray:
    w, h = size
    rng = np.random.default_rng(seed)
    base = np.array(WALLS[key]["rgb"], dtype=np.float32)
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    d = np.hypot((xx - 0.42 * w) / w, (yy - 0.30 * h) / h)
    light = 1.045 - 0.16 * (d / d.max()) ** 1.5
    mottling = 1 + 0.010 * _lowfreq((h, w), rng, 6)
    grain = ndimage.gaussian_filter(rng.standard_normal((h, w)).astype(np.float32), 1.0) * 5.0
    wall = base[None, None, :] * (light * mottling)[..., None] + grain[..., None]
    return np.clip(wall, 0, 255)


def room_background(path: Path, box: list[float], size: tuple[int, int] = CANVAS) -> tuple[np.ndarray, tuple[int, int, int, int]]:
    """Cover-crop a room photo to the canvas, keeping the placement box (normalized x0,y0,x1,y1) in view."""
    w, h = size
    img = Image.open(path).convert("RGB")
    scale = max(w / img.width, h / img.height)
    img = img.resize((math.ceil(img.width * scale), math.ceil(img.height * scale)), Image.LANCZOS)
    bx0, by0, bx1, by1 = [v * s for v, s in zip(box, (img.width, img.height, img.width, img.height))]
    cx, cy = (bx0 + bx1) / 2, (by0 + by1) / 2
    left = int(min(max(cx - w / 2, 0), img.width - w))
    top = int(min(max(cy - h / 2, 0), img.height - h))
    img = img.crop((left, top, left + w, top + h))
    # a box wider than the square crop is trimmed to it (the piece then hangs a little smaller)
    px_box = (max(0, int(bx0 - left)), max(0, int(by0 - top)), min(w, int(bx1 - left)), min(h, int(by1 - top)))
    return np.asarray(img, dtype=np.float32), px_box


# --- metal rendering ------------------------------------------------------------------------------

def _alpha(mask: np.ndarray, width: int, height: int) -> np.ndarray:
    img = Image.fromarray(np.where(mask, 255, 0).astype(np.uint8), mode="L")
    resample = Image.BOX if width < mask.shape[1] else Image.LANCZOS
    return np.asarray(img.resize((width, height), resample), dtype=np.float32) / 255.0


def _blur(a: np.ndarray, sigma: float) -> np.ndarray:
    """Gaussian blur; large radii run on a downsampled copy (shadows don't need full resolution)."""
    if sigma <= 8:
        return ndimage.gaussian_filter(a, max(sigma, 0.01))
    f = int(sigma // 4)
    h, w = a.shape
    small = np.asarray(Image.fromarray(a).resize((max(1, w // f), max(1, h // f)), Image.BOX), dtype=np.float32)
    small = ndimage.gaussian_filter(small, sigma / f)
    return np.asarray(Image.fromarray(small).resize((w, h), Image.BILINEAR), dtype=np.float32)


def _tone(tones: tuple[str, str, str], t: np.ndarray) -> np.ndarray:
    """t: 0 = shadow code, 0.5 = base code, 1 = highlight code; below 0 darkens past the shadow code."""
    lo, mid, hi = (_hex(c) for c in tones)
    t = t[..., None]
    a = np.clip(t / 0.5, 0, 1)
    b = np.clip((t - 0.5) / 0.5, 0, 1)
    rgb = np.where(t < 0.5, lo + (mid - lo) * a, mid + (hi - mid) * b)
    return rgb * (1 + np.clip(t, -0.35, 0))


TEXTURE = 0.02  # strength of the powder-coat surface on the tone scale


def _powder(shape: tuple[int, int], rng: np.random.Generator, s: int) -> np.ndarray:
    """Powder-coat surface, unit std: a soft orange-peel mottle and a fine metallic fleck, both without a
    direction, so the face is not glassy smooth yet shows no streaks."""
    h, w = shape
    peel = ndimage.gaussian_filter(rng.standard_normal((h, w)).astype(np.float32), max(1.5, s * 0.0025))
    fleck = ndimage.gaussian_filter(rng.standard_normal((h, w)).astype(np.float32), 0.8)
    out = 0.6 * peel / (peel.std() + 1e-6) + 0.4 * fleck / (fleck.std() + 1e-6)
    return out / (out.std() + 1e-6)


def metal_rgb(alpha: np.ndarray, finish: str, seed: int = 3, light: tuple[float, float] = (-0.36, -0.93),
              edge_px: float | None = None) -> np.ndarray:
    """Face color of the piece: broad light falloff, sheen, powder-coat surface, lit cut edges.
    edge_px: how soft the cut edge reads, in px; a thin sheet has a crisp edge with a hairline highlight."""
    spec = FINISHES[finish]
    m = spec["metallic"]
    h, w = alpha.shape
    s = max(h, w)
    rng = np.random.default_rng(seed)
    lx, ly = light
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    proj = (xx / w - 0.5) * lx + (yy / h - 0.5) * ly  # + toward the light
    t = 0.5 + (0.16 + 0.30 * m) * proj
    if m:
        t = t + m * (0.07 * _lowfreq((h, w), rng, 4) + 0.2 * np.exp(-((proj - 0.18) / 0.16) ** 2))
    if spec.get("texture"):
        t = t + spec["texture"] * TEXTURE * _powder((h, w), rng, s)
    bevel = edge_px if edge_px is not None else max(1.0, s * 0.0011)
    height = ndimage.gaussian_filter(alpha, bevel)
    gy, gx = np.gradient(height)
    facing = np.clip(-(gx * lx + gy * ly) * bevel * 3.0, -1, 1)
    t = t + facing * (0.32 + 0.22 * m)
    rgb = _tone(spec["tones"], t)
    grain = ndimage.gaussian_filter(rng.standard_normal((h, w)).astype(np.float32), 0.7)
    grain /= grain.std() + 1e-6
    rgb *= (1 + (0.005 + 0.007 * m) * grain)[..., None]
    return np.clip(rgb, 0, 255)


def _shift(a: np.ndarray, dx: int, dy: int) -> np.ndarray:
    out = np.zeros_like(a)
    h, w = a.shape
    if abs(dx) >= w or abs(dy) >= h:
        return out
    out[max(0, dy):h + min(0, dy), max(0, dx):w + min(0, dx)] = a[max(0, -dy):h - max(0, dy), max(0, -dx):w - max(0, dx)]
    return out


def dial_reach(mask: np.ndarray) -> float:
    """How far the hands may reach, as a fraction of the design's half short side (1.0 on a round clock).

    The hands belong to the dial, not to the whole design: on a wide piece (a clock inside a mountain
    scene) the dial is a small part of it. Walking out from the centre: the shaft hole, the solid centre,
    then the closed metal rings; the OUTERMOST one is the dial's rim (its inner edge counts). Rings inside
    it are decoration (a geometric clock's inner circles) and must not shrink the hands; past the rim of a
    clock in a scene the circles run through the scenery, so they are never closed. On a round clock the
    rim is the design's edge (inner edge at ~0.94 of the half side): 1.0. No ring: 1.0."""
    h, w = mask.shape
    yy, xx = np.ogrid[:h, :w]
    r = np.hypot(yy - (h - 1) / 2, xx - (w - 1) / 2).astype(np.int32).ravel()
    half = int(min(h, w) / 2)
    count = np.bincount(r, minlength=half)[:half]
    metal = np.bincount(r, weights=mask.ravel().astype(np.float32), minlength=half)[:half]
    full = metal / np.maximum(count, 1)  # share of metal on each circle around the centre
    phase = 0  # 0: shaft hole, 1: solid centre, 2: between rings, 3: on a ring
    rim = None  # inner edge of the latest ring
    for radius in range(1, half):
        f = full[radius]
        if phase == 0 and f >= 0.97:
            phase = 1
        elif phase == 1 and f < 0.9:
            phase = 2
        elif phase == 2 and f >= 0.97:
            phase, rim = 3, radius
        elif phase == 3 and f < 0.9:
            phase = 2
    return 1.0 if rim is None else float(min(1.0, max(0.25, rim / 0.94 / half)))


@lru_cache(maxsize=16)
def _clock_hands(width: int, height: int, reach: float = 1.0, ss: int = 2) -> tuple[np.ndarray, np.ndarray]:
    """Hands at 10:10:35 as two alpha layers the size of the placed design: (hour+minute, second).
    reach: the hands' radius as a fraction of the design's half short side (see dial_reach)."""
    cx, cy = width * ss / 2, height * ss / 2
    radius = min(width, height) * ss / 2 * reach

    def layer(draw_fn) -> np.ndarray:
        big = Image.new("L", (width * ss, height * ss), 0)
        draw_fn(ImageDraw.Draw(big))
        return np.asarray(big.resize((width, height), Image.BOX), dtype=np.float32) / 255.0

    def hand(draw: ImageDraw.ImageDraw, angle_deg: float, length: float, base_w: float, tail: float, tip_w: float = 0.25) -> None:
        a = math.radians(angle_deg)
        ux, uy = math.sin(a), -math.cos(a)
        px, py = -uy, ux
        tip = (cx + ux * length, cy + uy * length)
        back = (cx - ux * tail, cy - uy * tail)
        draw.polygon([
            (back[0] + px * base_w * 0.6, back[1] + py * base_w * 0.6),
            (cx + px * base_w, cy + py * base_w),
            (tip[0] + px * base_w * tip_w, tip[1] + py * base_w * tip_w),
            (tip[0] - px * base_w * tip_w, tip[1] - py * base_w * tip_w),
            (cx - px * base_w, cy - py * base_w),
            (back[0] - px * base_w * 0.6, back[1] - py * base_w * 0.6),
        ], fill=255)

    def main(draw: ImageDraw.ImageDraw) -> None:
        hand(draw, 305, radius * 0.50, radius * 0.032, radius * 0.09)  # hour
        hand(draw, 60, radius * 0.74, radius * 0.024, radius * 0.11)   # minute
        cap = radius * 0.045
        draw.ellipse((cx - cap, cy - cap, cx + cap, cy + cap), fill=255)

    def second(draw: ImageDraw.ImageDraw) -> None:
        hand(draw, 213, radius * 0.84, radius * 0.0075, radius * 0.22, tip_w=0.6)
        cap = radius * 0.022
        draw.ellipse((cx - cap, cy - cap, cx + cap, cy + cap), fill=255)

    return layer(main), layer(second)


def cover_scale(path: Path, size: tuple[int, int] = CANVAS) -> float:
    """How much room_background enlarges this photo (used to match the product's sharpness to it)."""
    with Image.open(path) as img:
        return max(size[0] / img.width, size[1] / img.height)


def _room_light(region: np.ndarray, footprint: tuple[slice, slice], size: int) -> tuple[np.ndarray, tuple[float, float], float]:
    """Read the photo's light where the piece hangs: light map (falloff x exposure x tint), direction, grain."""
    lum = region @ np.array([0.299, 0.587, 0.114], dtype=np.float32)
    lb = _blur(lum, size * 0.08) + 1.0
    foot = lb[footprint]
    illum = np.clip(lb / foot.mean(), 0.8, 1.2) ** 0.75
    half = foot.shape[1] // 2
    tilt = (foot[:, half:].mean() - foot[:, :half].mean()) / foot.mean()  # + brighter on the right
    lx = float(np.clip(tilt * 3.0, -0.8, 0.8)) if abs(tilt) > 0.03 else -0.36
    norm = math.hypot(lx, 1.0)
    light = (lx / norm, -1.0 / norm)
    p95 = float(np.percentile(lum, 95))
    tint = np.ones(3, dtype=np.float32)
    if p95 > 150:
        c = region[lum >= p95].mean(axis=0)
        tint = np.clip(1 + 0.4 * (c / c.mean() - 1), 0.93, 1.07).astype(np.float32)
    # a dark photo dims the piece only slightly (at most 3%): a dark wall paint (charcoal, navy) also reads
    # as a dark photo here, and dimming the metal with it made every finish look dull
    exposure = float(np.clip(np.percentile(lum, 97) / 225, 0.85, 1.0) ** 0.2)
    patch = lum[footprint]
    hp = patch - ndimage.gaussian_filter(patch, 1.5)
    grain = min(2.0, 0.6 * float(1.4826 * np.median(np.abs(hp - np.median(hp)))))  # wall texture inflates it
    return illum[..., None] * exposure * tint, light, grain


PLATE = 1.5 / 762  # sheet thickness / design width when the caller does not say (1.5 mm steel, 30")
# A 1.5 mm sheet must not read as a 1 cm slab. What made it look thick: a sharp dark
# shadow band hugging every edge (a ~1 cm standoff with a shadow sharper than its offset reads as a side
# wall) and a rounded lit/shaded rim on the face (reads as a pillowed edge). Now the sheet sits a few mm
# off the wall with a shadow softer than its offset, and the face stays flat right up to a crisp cut.
EDGE_VIEW = 0.2    # share of the sheet's thickness a camera at eye level sees of the underside
EDGE_ROUND = 0.12  # how far the lit/shaded rim of the face reaches in from the cut, as a share of the
                   # thickness (~0.2 mm on 1.5 mm: the coating's tiny radius, not a bevel)
STANDOFF = 0.006   # gap between the sheet and the wall, as a share of the design's size (~4.5 mm on 30")
CAST = (1.0, 1.5, 0.45)   # main cast shadow: offset (x gap), blur (x gap), strength
WIDE = (2.5, 5.0, 0.22)   # broad ambient shadow: offset (x gap), blur (x gap), strength


def scene(mask: np.ndarray, finish: str, background: np.ndarray, box: tuple[int, int, int, int],
          clock: bool = False, hands_finish: str | None = None, seed: int = 3, bg_scale: float = 1.0,
          plate: float = PLATE) -> np.ndarray:
    """Hang the design (fit inside box) on the background as a real piece: it takes the room's light,
    stands off the wall (soft cast shadow), shows its cut edge, and matches the photo's sharpness.
    plate: sheet thickness / design width. The cut edge and its highlight are drawn at that real
    thickness, so a 1.5 mm sheet reads as a thin sheet, not a slab."""
    canvas = background.copy()
    ch, cw = canvas.shape[:2]
    mh, mw = mask.shape
    bx0, by0, bx1, by1 = box
    bw, bh = bx1 - bx0, by1 - by0
    tw = int(min(bw, bh * mw / mh))
    th = max(1, int(tw * mh / mw))
    x0 = int(bx0 + (bw - tw) / 2)
    y0 = int(by0 + (bh - th) / 2)
    size = max(tw, th)
    margin = int(size * 0.12) + 16
    ry0, ry1 = max(0, y0 - margin), min(ch, y0 + th + margin)
    rx0, rx1 = max(0, x0 - margin), min(cw, x0 + tw + margin)
    region = canvas[ry0:ry1, rx0:rx1]
    oy, ox = y0 - ry0, x0 - rx0
    ys = slice(max(0, oy), min(region.shape[0], oy + th))
    xs = slice(max(0, ox), min(region.shape[1], ox + tw))
    src = (slice(ys.start - oy, ys.stop - oy), slice(xs.start - ox, xs.stop - ox))
    light_map, light, grain = _room_light(region, (ys, xs), size)
    sx, sy = -light[0], -light[1]  # shadows fall away from the light

    layers = [(_alpha(mask, tw, th), finish, 1.0, True)]
    if clock:
        main, second = _clock_hands(tw, th, round(dial_reach(mask), 3))
        hf = hands_finish or hands_for(finish)
        layers += [(main, hf, 1.9, False), (second, hf, 2.4, False)]
    gap0 = size * STANDOFF  # standoff gap of the face, in px
    # cut edge seen from a camera at eye level, below and near the middle: the underside shows, as wide as
    # the sheet's real thickness allows (usually under a pixel: drawn as a faint hairline)
    ex = float(np.clip((cw / 2 - (x0 + tw / 2)) / cw * 1.2, -0.5, 0.5))
    sheet_px = plate * tw
    underside = sheet_px * EDGE_VIEW
    edge_soft = max(0.6, sheet_px * EDGE_ROUND)
    product = np.zeros(region.shape[:2], dtype=np.float32)
    for alpha, fin, lift, edge in layers:
        full = np.zeros(region.shape[:2], dtype=np.float32)
        full[ys, xs] = alpha[src]
        g = gap0 * lift
        # a thin sheet held off the wall: a soft cast shadow, no dark rim hugging the edges
        cast = _blur(_shift(full, round(g * CAST[0] * sx), round(g * CAST[0] * sy)), max(1.0, g * CAST[1]))
        wide = _blur(_shift(full, round(g * WIDE[0] * sx), round(g * WIDE[0] * sy)), max(1.0, g * WIDE[1]))
        contact = _blur(_shift(full, round(g * 0.12 * sx), round(g * 0.12 * sy) + 1), max(0.8, g * 0.12))
        shadow = 1 - (1 - CAST[2] * cast) * (1 - WIDE[2] * wide) * (1 - 0.08 * contact)
        region *= (1 - shadow)[..., None]
        if edge:
            side = np.zeros_like(full)
            for k in range(1, max(1, round(underside)) + 1):
                side = np.maximum(side, _shift(full, round(k * ex), k))
            side *= min(1.0, underside)  # thinner than a pixel: a faint line
            side_rgb = _tone(FINISHES[fin]["tones"], np.full(side.shape, -0.1, dtype=np.float32)) * light_map
            region = region * (1 - side[..., None]) + side_rgb * side[..., None]
            product = np.maximum(product, side)
        metal = np.zeros_like(region)
        metal[ys, xs] = metal_rgb(alpha, fin, seed, light, edge_soft if edge else None)[src]
        region = region * (1 - full[..., None]) + metal * light_map * full[..., None]
        product = np.maximum(product, full)
    # match the photo: same softness and grain on the piece as on the wall around it
    sigma = 0.42 * max(1.0, bg_scale)
    weight = np.clip(np.maximum(product, _blur(product, 2 * sigma) * 2.5), 0, 1)[..., None]
    soft = np.stack([ndimage.gaussian_filter(region[..., c], sigma) for c in range(3)], axis=-1)
    region = region * (1 - weight) + soft * weight
    if grain > 0.3:
        rng = np.random.default_rng(seed + 101)
        noise = ndimage.gaussian_filter(rng.standard_normal(region.shape[:2]).astype(np.float32), 0.45 * max(1.0, bg_scale))
        noise *= grain / (noise.std() + 1e-6)
        region = region + noise[..., None] * weight
    canvas[ry0:ry1, rx0:rx1] = region
    return np.clip(canvas, 0, 255)


def to_image(arr: np.ndarray) -> Image.Image:
    return Image.fromarray(arr.astype(np.uint8), mode="RGB")


def save_jpg(img: Image.Image, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "JPEG", quality=90, optimize=True, progressive=True)


