def _flat_design(mask: np.ndarray, width: int, color: tuple[int, int, int], hands: str | None = None,
                 reach: float = 1.0) -> Image.Image:
    """The design as a flat silhouette; clocks get their hands on top in the given finish's colour."""
    height = max(1, int(width * mask.shape[0] / mask.shape[1]))
    alpha = Image.fromarray((_alpha(mask, width, height) * 255).astype(np.uint8), mode="L")
    tile = Image.new("RGBA", (width, height), (*color, 0))
    tile.putalpha(alpha)
    if hands:
        main, second = _clock_hands(width, height, round(reach, 3))
        top = Image.new("RGBA", (width, height), (*_hex(FINISHES[hands]["tones"][1]).astype(int).tolist(), 0))
        top.putalpha(Image.fromarray((np.maximum(main, second) * 255).astype(np.uint8), mode="L"))
        tile = Image.alpha_composite(tile, top)
    return tile


def finishes_card(mask: np.ndarray, finishes: list[str], clock: bool = False, plate: float = PLATE) -> Image.Image:
    w, h = CANVAS
    canvas = plain_wall("greige", seed=11)
    n = len(finishes)
    side, gap = 150, 90
    cols = n if n <= 3 else math.ceil(n / 2)
    rows = math.ceil(n / cols)
    cell_w = (w - 2 * side - gap * (cols - 1)) / cols
    area_top, area_bottom = 420, h - 110
    row_h = (area_bottom - area_top) / rows
    aspect = mask.shape[0] / mask.shape[1]
    label_h = 140
    tile_w = min(cell_w, (row_h - label_h - 60) / aspect)
    tile_h = tile_w * aspect
    label = font("Inter.ttf", 74)
    spots = []
    for i, fin in enumerate(finishes):
        r, c = divmod(i, cols)
        in_row = min(cols, n - r * cols)
        row_w = in_row * cell_w + (in_row - 1) * gap
        cx = (w - row_w) / 2 + c * (cell_w + gap) + cell_w / 2
        y_top = area_top + r * row_h + (row_h - tile_h - label_h) / 2
        box = (int(cx - tile_w / 2), int(y_top), int(cx + tile_w / 2), int(y_top + tile_h))
        canvas = scene(mask, fin, canvas, box, clock=clock, seed=3 + i, plate=plate)
        spots.append((cx, y_top + tile_h + label_h / 2 + 24, fin))
    img = to_image(canvas)
    draw = ImageDraw.Draw(img)
    draw.text((w / 2, 230), "Available Finishes", font=font("PlayfairDisplay.ttf", 150), fill=INK, anchor="mm")
    for cx, cy, fin in spots:
        draw.text((cx, cy), FINISHES[fin]["label"], font=label, fill=INK, anchor="mm")
    return img


def _size_rows(sizes: list[float], per_row_max: int = 5) -> list[list[float]]:
    """Ascending sizes in balanced rows of at most per_row_max (10 sizes -> 5 + 5, 7 -> 4 + 3)."""
    rows = max(1, math.ceil(len(sizes) / per_row_max))
    per_row = math.ceil(len(sizes) / rows)
    return [sizes[i:i + per_row] for i in range(0, len(sizes), per_row)]


def size_card(mask: np.ndarray, sizes_in: list[float], clock: bool = False) -> Image.Image:
    """Every size of the design to one common scale, smallest first, in rows of up to five. The pieces are
    black silhouettes, so a clock's hands are gold, as on the black clock."""
    w, h = CANVAS
    img = to_image(plain_wall("warm-white", seed=5))
    draw = ImageDraw.Draw(img)
    draw.text((w / 2, 230), "Size Guide", font=font("PlayfairDisplay.ttf", 150), fill=INK, anchor="mm")
    sizes = sorted({float(s) for s in sizes_in if s and s > 0}) or [1.0]
    aspect = mask.shape[0] / mask.shape[1]
    side, gap, row_gap = 140, 70, 130
    label_w, label_h = 360, 250  # room the three text lines need under each piece
    area_top, area_bottom = 420, h - 230

    def fits(rows: list[list[float]], unit: float) -> bool:
        for row in rows:
            if sum(max(s * unit, label_w) for s in row) + gap * (len(row) - 1) > w - 2 * side:
                return False
        total = sum(max(row) * aspect * unit + label_h for row in rows) + row_gap * (len(rows) - 1)
        return total <= area_bottom - area_top

    def best_unit(rows: list[list[float]]) -> float:
        lo, hi = 0.0, (w - 2 * side) / min(sizes)
        for _ in range(40):  # largest common scale that fits
            mid = (lo + hi) / 2
            lo, hi = (mid, hi) if fits(rows, mid) else (lo, mid)
        return lo

    # up to 2-5 per row: wide pieces grow with fewer per row, round ones with more; keep the biggest scale
    layouts = [_size_rows(sizes, k) for k in range(5, 1, -1)]
    unit, rows = max(((best_unit(rows), rows) for rows in layouts), key=lambda item: item[0])
    label, small = font("Inter.ttf", 64), font("Inter.ttf", 48)
    hands, reach = (hands_for("black"), dial_reach(mask)) if clock else (None, 1.0)
    total = sum(max(row) * aspect * unit + label_h for row in rows) + row_gap * (len(rows) - 1)
    y = area_top + (area_bottom - area_top - total) / 2
    for row in rows:
        baseline = y + max(row) * aspect * unit
        slots = [max(s * unit, label_w) for s in row]
        x = (w - sum(slots) - gap * (len(row) - 1)) / 2
        for s, slot in zip(row, slots):
            cx = x + slot / 2
            tile = _flat_design(mask, max(8, int(s * unit)), (40, 40, 42), hands, reach)
            img.paste(tile, (int(cx - tile.width / 2), int(baseline - tile.height)), tile)
            d = dims(s, aspect)  # same labels as the listing, kit and workshop note
            draw.text((cx, baseline + 75), d["label_w"], font=label, fill=INK, anchor="mm")
            draw.text((cx, baseline + 150), d["label_in"], font=small, fill=MUTED, anchor="mm")
            draw.text((cx, baseline + 210), d["label_cm"], font=small, fill=MUTED, anchor="mm")
            x += slot + gap
        y = baseline + label_h + row_gap
    draw.text((w / 2, h - 120), "Width × height, measured edge to edge", font=small, fill=MUTED, anchor="mm")
    return img


def detail_crop(mask: np.ndarray, finish: str, wall: str, clock: bool = False, zoom: float = 1.8,
                plate: float = PLATE) -> Image.Image:
    """Re-render larger and crop around the busiest area (edges = detail)."""
    w, h = CANVAS
    big_w = int(w * 0.62 * zoom)
    big_h = int(big_w * mask.shape[0] / mask.shape[1])
    pad = int(w * 0.15)
    bw, bh = max(big_w + 2 * pad, w), max(big_h + 2 * pad, h)  # always larger than the crop
    ox, oy = (bw - big_w) // 2, (bh - big_h) // 2
    bg = plain_wall(wall, (bw, bh), seed=9)
    arr = scene(mask, finish, bg, (ox, oy, ox + big_w, oy + big_h), clock=clock, plate=plate)
    small = _alpha(mask, max(1, big_w // 8), max(1, big_h // 8))
    edges = ndimage.gaussian_filter(np.abs(np.gradient(small)[0]) + np.abs(np.gradient(small)[1]), 3)
    if clock:  # keep the center hub and hands in frame
        cy, cx = small.shape[0] / 2, small.shape[1] / 2
    else:
        cy, cx = np.unravel_index(int(np.argmax(edges)), edges.shape)
    cx = ox + cx * 8
    cy = oy + cy * 8
    left = int(min(max(cx - w / 2, 0), bw - w))
    top = int(min(max(cy - h / 2, 0), bh - h))
    return to_image(arr[top:top + h, left:left + w])


