# The piece as large as it goes, "Details" under it and a ruled spec table.

DETAILS_TITLE = ("CormorantGaramond.ttf", 206, "SemiBold")  # font() arguments: file, size, weight
DETAILS_KEY = ("Montserrat.ttf", 42, "SemiBold")
DETAILS_VALUE = ("Montserrat.ttf", 66, "Regular")
DETAILS_FONTS = ("Cormorant Garamond", "Montserrat")  # license names (LISANSLAR.md)
RULE = (196, 186, 168)  # hairlines between the rows of the spec table


def info_rows(facts: dict, product_type: str, sizes_in: list[float]) -> list[tuple[str, str]]:
    """The card's fields. Sizes as a range with cm (16 sizes, 19.7"–77.2" wide (50–196 cm)): every size
    is on the Size Guide image, a list of sixteen does not read on a phone."""
    rows = []
    material = facts.get("material", "")
    if material:
        thickness = facts.get("thickness_mm")
        rows.append(("Material", f"{thickness:g} mm {material}" if thickness else material))
    if facts.get("coating"):
        rows.append(("Finish", facts["coating"]))
    sizes = sorted(sizes_in or [])
    if sizes:
        lo, hi = dims(sizes[0], None), dims(sizes[-1], None)
        lo_cm, hi_cm = (d["label_cm"].replace(" wide", "") for d in (lo, hi))
        rows.append(("Sizes", f'{lo["label_w"]} wide ({lo_cm})' if len(sizes) == 1 else
                     f'{len(sizes)} sizes, {lo["label_w"]}–{hi["label_w"]} wide ({lo_cm.removesuffix(" cm")}–{hi_cm})'))
    if facts.get("mounting"):
        rows.append(("Mounting", facts["mounting"]))
    if product_type == "saat" and facts.get("clock_movement"):
        rows.append(("Clock", facts["clock_movement"]))
    if facts.get("indoor_outdoor"):
        rows.append(("Use", facts["indoor_outdoor"].capitalize()))
    if facts.get("care"):
        rows.append(("Care", facts["care"]))
    return rows


def _spaced(draw: ImageDraw.ImageDraw, xy: tuple[float, float], text: str, fnt: ImageFont.FreeTypeFont,
            fill: tuple[int, int, int], tracking: float) -> None:
    """Text with letter spacing (Pillow has none)."""
    x, y = xy
    for c in text:
        draw.text((x, y), c, font=fnt, fill=fill)
        x += draw.textlength(c, font=fnt) + tracking


def _table(draw: ImageDraw.ImageDraw, rows: list[tuple[str, str]], x0: float, y0: float, width: float,
           paint: bool = True) -> float:
    """Field name left, value right, a hairline between rows (a spec sheet). Returns the height used."""
    kf, vf = font(*DETAILS_KEY), font(*DETAILS_VALUE)
    key_w = 520
    line_h, pad = int(vf.size * 1.3), int(vf.size * 0.62)
    y = y0
    for i, (key, value) in enumerate(rows):
        lines = _wrap(draw, value, vf, int(width - key_w))
        if paint:
            if i:
                draw.line((x0, y, x0 + width, y), fill=RULE, width=3)
            _spaced(draw, (x0, y + pad + (vf.size - kf.size) * 0.55), key.upper(), kf, MUTED, 4)
            for j, line in enumerate(lines):
                draw.text((x0 + key_w, y + pad + j * line_h), line, font=vf, fill=INK)
        y += line_h * len(lines) + 2 * pad
    return y - y0


def info_card(mask: np.ndarray, finish: str, facts: dict, product_type: str, sizes_in: list[float],
              plate: float = PLATE) -> Image.Image:
    w, h = CANVAS
    rows = info_rows(facts, product_type, sizes_in)
    title_h, table_x, bottom = int(DETAILS_TITLE[1] * 1.25), 420, 170
    probe = ImageDraw.Draw(Image.new("RGB", (8, 8)))
    text_h = title_h + 30 + _table(probe, rows, 0, 0, w - 2 * table_x, paint=False)
    y = h - bottom - text_h  # the text block sits at the bottom; the piece takes everything above it
    canvas = scene(mask, finish, plain_wall("cream", seed=13), (160, 130, w - 160, int(y - 100)),
                   clock=product_type == "saat", plate=plate)
    img = to_image(canvas)
    draw = ImageDraw.Draw(img)
    draw.text((w / 2, y), "Details", font=font(*DETAILS_TITLE), fill=INK, anchor="ma")
    _table(draw, rows, table_x, y + title_h + 30, w - 2 * table_x)
    return img


def _wrap(draw: ImageDraw.ImageDraw, text: str, fnt: ImageFont.FreeTypeFont, max_w: int) -> list[str]:
    words, lines, line = text.split(), [], ""
    for word in words:
        trial = f"{line} {word}".strip()
        if draw.textlength(trial, font=fnt) <= max_w:
            line = trial
        else:
            if line:
                lines.append(line)
            line = word
    if line:
        lines.append(line)
    return lines or [""]
